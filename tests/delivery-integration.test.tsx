import { render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { MemoryRouter } from 'react-router-dom';
import { expect, test } from 'vitest';
import { AppRoutes } from '../src/App';
import { createTestApplicationServices } from './doubles/applicationServices';

test('cadastro login nota publicação edição favoritos e logout percorrem serviços integrados', async () => {
  const adapters = createTestApplicationServices();
  const interaction = userEvent.setup();
  render(<MemoryRouter initialEntries={['/cadastro']}><AppRoutes adapters={adapters} /></MemoryRouter>);
  await interaction.type(screen.getByRole('textbox', { name: 'Nome' }), 'Demonstração');
  await interaction.type(screen.getByRole('textbox', { name: 'E-mail' }), 'demo@example.com');
  await interaction.type(screen.getByLabelText('Senha'), 'teste123');
  await interaction.click(screen.getByRole('button', { name: 'Criar conta' }));
  await screen.findByRole('form', { name: 'Login' });
  await interaction.type(screen.getByRole('textbox', { name: 'E-mail' }), 'demo@example.com');
  await interaction.type(screen.getByLabelText('Senha'), 'teste123');
  await interaction.click(screen.getByRole('button', { name: 'Entrar' }));
  await interaction.click(await screen.findByRole('link', { name: 'Jogo de exemplo' }));
  await interaction.click(await screen.findByRole('radio', { name: '5 estrelas' }));
  await interaction.click(screen.getByRole('button', { name: 'Salvar nota' }));
  expect(await screen.findByText('Nota 5 salva.')).toBeVisible();
  await interaction.click(await screen.findByRole('button', { name: 'Favoritar jogo' }));
  await interaction.type(await screen.findByRole('textbox', { name: 'Sua review' }), 'Primeira review da demonstração');
  await interaction.click(screen.getByRole('button', { name: 'Publicar review' }));
  await interaction.click(await screen.findByRole('link', { name: 'Editar minha review' }));
  await interaction.clear(await screen.findByRole('textbox', { name: 'Sua review' }));
  await interaction.type(screen.getByRole('textbox', { name: 'Sua review' }), 'Review revisada da demonstração');
  await interaction.click(screen.getByRole('button', { name: 'Salvar review' }));
  expect(await screen.findByText('Review atualizada.')).toBeVisible();
  await interaction.click(await screen.findByRole('button', { name: 'Favoritar review' }));
  await interaction.click(screen.getByRole('link', { name: 'Meu perfil' }));
  const games = await screen.findByRole('region', { name: 'Jogos favoritos' });
  expect(within(games).getByRole('link', { name: 'Ecos do Horizonte' })).toBeVisible();
  expect(within(screen.getByRole('region', { name: 'Reviews favoritas' })).getByText('Review revisada da demonstração')).toBeVisible();
  await interaction.click(screen.getByRole('link', { name: 'Início' }));
  await interaction.click(screen.getByRole('link', { name: 'Jogo de exemplo' }));
  expect(await screen.findByRole('radio', { name: '5 estrelas' })).toBeChecked();
  await interaction.click(screen.getByRole('button', { name: 'Sair' }));
  expect(screen.queryByRole('button', { name: 'Notificações' })).not.toBeInTheDocument();
  expect(screen.queryByRole('button', { name: 'Salvar nota' })).not.toBeInTheDocument();
}, 15000);

test('busca review comentário seguir feed e notificações funcionam sem spies de serviço', async () => {
  const adapters = createTestApplicationServices();
  const interaction = userEvent.setup();
  render(<MemoryRouter initialEntries={['/login']}><AppRoutes adapters={adapters} /></MemoryRouter>);
  await interaction.type(screen.getByRole('textbox', { name: 'E-mail' }), 'ana@example.com');
  await interaction.type(screen.getByLabelText('Senha'), 'teste123');
  await interaction.click(screen.getByRole('button', { name: 'Entrar' }));
  await interaction.type(await screen.findByRole('textbox', { name: 'Buscar jogos' }), 'Ecos');
  await interaction.keyboard('{Enter}');
  await interaction.click(await screen.findByRole('link', { name: 'Ecos do Horizonte' }));
  await interaction.click(await screen.findByRole('link', { name: 'Review de Leo' }));
  await interaction.type(await screen.findByRole('textbox', { name: 'Seu comentário' }), 'Comentário integrado');
  await interaction.click(screen.getByRole('button', { name: 'Publicar comentário' }));
  expect(await screen.findByText('Comentário integrado')).toBeVisible();
  await interaction.click(screen.getByRole('link', { name: 'Leo' }));
  await interaction.click(await screen.findByRole('button', { name: 'Seguir Leo' }));
  await screen.findByRole('button', { name: 'Deixar de seguir Leo' });
  await interaction.click(screen.getByRole('link', { name: 'Início' }));
  const feed = await screen.findByRole('region', { name: 'Feed de reviews' });
  expect(await within(feed).findByText('Um mundo pequeno, mas cheio de detalhes para descobrir.')).toBeVisible();
  await interaction.click(screen.getByRole('button', { name: 'Notificações' }));
  const dialog = screen.getByRole('dialog');
  expect(within(dialog).getByRole('button', { name: 'Fechar notificações' })).toHaveFocus();
  await interaction.click(await within(dialog).findByRole('link', { name: /Leo comentou na sua review/ }));
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
  expect(await screen.findByRole('textbox', { name: 'Sua review' })).toBeVisible();
}, 15000);
